"""Single immutable V2 capability and worker contract."""
import re
from types import MappingProxyType

class ContractError(ValueError):
    pass

# Arguments, effect class (read / write / confirm / save), recognised vocabulary. The model interprets requests;
# a vocabulary match only lets a write action skip the interpretation check. A
# miss never rejects a request: it routes the plan to driver confirmation.
SAVE_WORDS = r'\b(?:remember|save|store|update|change|set)\b'
_CAPABILITIES = {
 'media.play': ({'query':'text'}, 'write', r'\b(?:play|put on|listen|music|song|playlist|mets|jazz)\b'),
 'media.pause': ({}, 'write', r'pause|stop.*(?:music|audio|playback)'),
 'media.next_track': ({}, 'write', r'skip|next (?:song|track)'),
 'navigation.start': ({'destination':'location'}, 'write', r'navigat(?:e|ion)|take me|drive|directions|go to'),
 'navigation.add_stop': ({'stop':'location'}, 'write', r'\b(?:stops?|via|on the way|waypoints?)\b'),
 'navigation.get_destination': ({}, 'read', r'destination|where.*going'),
 'phone.call': ({'contact':'person'}, 'confirm', r'call|dial|phone'),
 'phone.end_call': ({}, 'write', r'end.*call|hang up'),
 'messaging.send': ({'contact':'person','message':'text'}, 'confirm', r'send|text|message'),
 'calendar.next_appointment': ({}, 'read', r'appointment|calendar|meeting'),
 'vehicle.get_trip_state': ({}, 'read', r'battery|range|vehicle|charge level'),
 'messages.latest': ({'contact':'person'}, 'read', r'read|latest|last message'),
 # Saves change the driver's private profile: always confirmed, and every value must be the
 # driver's own words ("literal" arguments are never replaced by a database lookup).
 'profile.save_preference': ({'preference':'literal','value':'literal'}, 'save', SAVE_WORDS),
 'profile.save_contact': ({'relation':'literal','name':'literal','detail':'literal'}, 'save', SAVE_WORDS),
 'profile.save_place': ({'name':'literal','place':'literal'}, 'save', SAVE_WORDS),
}
CAPABILITIES = MappingProxyType({name: (MappingProxyType(args), effect, pattern)
                                for name, (args, effect, pattern) in _CAPABILITIES.items()})
del _CAPABILITIES
VERSION = 'v2-capabilities-3'

def task_text(prompt):
    """Separate a leading routing instruction from its colon-delimited task.

    This never authorizes cloud access. The original request remains the audit
    record and action evidence must still be a substring of it.
    """
    prefix=re.match(r'\s*(?:ignore\b[^:]*routing[^:]*|use\b[^:]*cloud[^:]*|keep (?:this|it) local)\s*:\s*',prompt,re.I)
    return prompt[prefix.end():] if prefix else prompt

# Execution/grounding checks, not route selection. State questions require an
# adapter receipt; a fluent model answer is not evidence of application state.
APPLICATION_READ_REQUESTS = (
    r"\b(?:my|our|current|remaining)\s+(?:battery|charge level|destination|next appointment|latest message)\b",
    r"\b(?:battery level|where am i going)\b",
)

def validate_answer_grounding(prompt):
    if any(re.search(pattern,prompt,re.I) for pattern in APPLICATION_READ_REQUESTS):
        raise ContractError('Application-state answer requires a verified read capability')

def worker_schema():
    """Use typed alternatives supported by the installed Ollama grammar.

    Each capability has its own argument object. Extra contact arguments for
    end_call, duplicate destinations, and mixed plan/answer objects cannot be
    generated by a schema-compliant provider. Python still validates everything.
    """
    def obj(properties):
        return {'type':'object','properties':properties,'required':list(properties),'additionalProperties':False}
    def literal(text):return {'type':'string','enum':[text]}
    text={'type':'string'}
    steps=[obj({'capability':literal(cap),'arguments':obj({key:text for key in args}),'evidence':text})
           for cap,(args,_,_) in CAPABILITIES.items()]
    from .tools import tool_schema
    return {'anyOf':[
        obj({'kind':literal('plan'),'steps':{'type':'array','minItems':1,'maxItems':8,'items':{'anyOf':steps}}}),
        obj({'kind':literal('answer'),'answer':text}),
        obj({'kind':literal('unsupported'),'reason':text}),
        obj({'kind':literal('clarification'),'slot':{'type':'string','enum':['person','location','preference','text']},'reference':text,'question':text}),
        obj({'kind':literal('tool_request'),'request':tool_schema()}),
    ]}


def normalize_wire(value):
    return validate_worker(value)


def validate_worker(value):
    if not isinstance(value,dict): raise ContractError('Worker result must be an object')
    kind=value.get('kind')
    keys={'answer':{'kind','answer'},'unsupported':{'kind','reason'},'clarification':{'kind','slot','reference','question'},'plan':{'kind','steps'},'tool_request':{'kind','request'}}
    if kind not in keys or set(value)!=keys[kind]: raise ContractError('Invalid worker result fields')
    if kind=='plan':
        if not isinstance(value['steps'],list) or not 1<=len(value['steps'])<=8: raise ContractError('Plan requires 1–8 steps')
        for step in value['steps']:
            if not isinstance(step,dict) or set(step)!={'capability','arguments','evidence'}: raise ContractError('Invalid action step')
            cap=step['capability']; args=step['arguments']
            if cap not in CAPABILITIES or not isinstance(args,dict) or set(args)!=set(CAPABILITIES[cap][0]): raise ContractError('Unapproved capability or arguments')
            for text in [step['evidence'],*args.values()]:
                if not isinstance(text,str) or len(text)>2000: raise ContractError('Invalid action value')
            if not step['evidence'].strip(): raise ContractError('Action requires request evidence')
    elif kind=='tool_request':
        from .tools import validate_tool_request
        validate_tool_request(value)
    else:
        for key,text in value.items():
            if not isinstance(text,str) or len(text)>6000: raise ContractError('Invalid response text')
        if kind=='answer' and not value['answer'].strip(): raise ContractError('Empty answer')
        if kind=='unsupported' and not value['reason'].strip(): raise ContractError('Empty unsupported reason')
        if kind=='clarification' and (value['slot'] not in {'person','location','preference','text'} or not value['question'].strip()): raise ContractError('Invalid clarification')
    return value

# Requests are judged clause by clause: a rule applies to the action a clause asks for,
# not to any word that happens to appear somewhere in the prompt.
CLAUSE_BREAK = re.compile(r'[.;!?\n]+|,|\s+(?:and then|then|and)\s+', re.I)
LEAD_IN = re.compile(r"^\s*(?:(?:please|kindly|hey|ok|okay)\s*,?\s+|(?:can|could|would|will) you\s+|"
                     r"i(?:'d| would) like to\s+|i (?:want|need) to\s+|let's\s+|go ahead and\s+)*", re.I)
QUESTION = re.compile(r'\s*(?:explain|what|how|compare|discuss|why|is|are|can i|should i)\b', re.I)
REFUSED = re.compile(
    r"(?:buy|purchase|order|pay)\b"
    r"|(?:lock|unlock)\b.*\b(?:doors?|car|vehicle|trunk)\b"
    r"|(?:turn|switch)\s+(?:on|off)\b.*\b(?:heated seats?|seat heat\w*|climate|temperature|air conditioning|a/?c|heater|heat)\b"
    r"|(?:set|adjust|raise|lower|increase|decrease)\b.*\b(?:heated seats?|climate|temperature|air conditioning|a/?c|heater|heat)\b", re.I)

def clauses(text):
    """(start, end) spans of the clauses of a request: split at sentence ends, commas, "and", "then"."""
    spans, start = [], 0
    for match in CLAUSE_BREAK.finditer(text):
        if text[start:match.start()].strip(): spans.append((start, match.start()))
        start = match.end()
    if text[start:].strip(): spans.append((start, len(text)))
    return spans

def clause_body(text):
    """A clause without its polite lead-in ("please", "can you", "I want to")."""
    return text[LEAD_IN.match(text).end():].strip()

def unsupported_action(prompt):
    """True when a clause *asks for* a purchase, payment, lock or climate change.

    Only the clause's own verb counts: "Navigate to Best Buy", "to order lunch" or
    "tell her to buy milk" are not purchases. Questions about these subjects are allowed.
    """
    if QUESTION.match(prompt): return False
    from .cleanup import lexicon
    text = prompt
    for brand in sorted(lexicon()['brands_flat'], key=len, reverse=True):
        text = re.sub(r'(?<!\w)' + re.escape(brand) + r'(?!\w)', 'Place', text, flags=re.I)
    return any(REFUSED.match(clause_body(text[a:b])) for a, b in clauses(text))

def clarification_grounded(value,request_text):
    '''A clarification must name one short phrase from the request (or nothing, for an
    argument never mentioned). A "reference" spanning sentences of supplied detail is
    the model asking for information it already has.'''
    reference=' '.join(re.findall(r'\w+',value['reference'].casefold()))
    if not reference:return True
    return len(reference.split())<=6 and reference in ' '.join(re.findall(r'\w+',request_text.casefold()))

def grounded_in(value,prompt):
    '''True when every word of an argument value appears in the request text.

    Articles carry no meaning of their own, so a model adding "the" ("the nearest
    McDonald's" for "nearest McDonald's") does not make a value ungrounded.
    '''
    words=lambda text:set(re.findall(r'\w+',text.casefold()))
    value_words=words(value)-{'the','a','an'}
    return bool(value_words) and value_words<=words(prompt)

NEGATION = re.compile(r"\b(?:do not|don't|dont|never|avoid|without)\b", re.I)
STRICT_NEGATION = re.compile(r"\b(?:do not|don't|dont|never)\b", re.I)
DRAFTING = re.compile(r'(?:plan|draft|write|explain|compare|recommend|suggest|report|summari[sz]e|describe)\b', re.I)

# "Compare two routes, then navigate to the faster one": a question that explicitly also asks for an action.
EXPLICIT_ACTION = re.compile(r'\b(?:then|and)\s+(?:send|call|navigate|play)\b', re.I)

# Questions in general (wider than QUESTION, which only exempts questions from the purchase/lock gate).
ASKING = re.compile(r'\s*(?:explain|what|how|compare|discuss|why|which|where|when|who|whose|is|are|am|was|were|does|do|did|'
                    r'has|have|can i|could i|should i|would it|will it|is it)\b', re.I)
TIMING = re.compile(r'\b(?:compare|faster|fastest|quicker|quickest|closer|closest|nearer|shorter|shortest|how long|how far|'
                    r'minutes?|hours?|time|order|before|after|on the way|fit|in time)\b', re.I)
ACTION_START = re.compile(r'(?:navigate|take me|drive|go|head|route|call|ring|dial|phone|text|message|send|play|pause|skip|'
                          r'stop|add|start|resume|find|show)\b', re.I)

def informational_request(prompt):
    """True when the request asks a question or for a comparison/recommendation rather than an action."""
    text = task_text(prompt); spans = clauses(text)
    if not spans or unsupported_action(text): return False
    first = clause_body(text[spans[0][0]:spans[0][1]])
    return bool(ASKING.match(first) or DRAFTING.match(first))

def travel_question(prompt):
    """A question about times, order or distance ("Starting from home, is it faster to…",
    "I have 40 minutes before…"), as opposed to a command: no clause starts with an action verb."""
    if informational_request(prompt): return True
    text = task_text(prompt)
    return bool(TIMING.search(text)) and not unsupported_action(text) and not any(
        ACTION_START.match(clause_body(text[a:b])) for a, b in clauses(text))

def evidence_region(evidence, prompt):
    """The clauses of the prompt that hold the evidence (the whole prompt when it is paraphrased)."""
    found = prompt.casefold().find(evidence.strip().casefold()) if evidence.strip() else -1
    spans = clauses(prompt)
    if found < 0: return spans
    end = found + len(evidence.strip())
    return [(a, b) for a, b in spans if a < end and found < b] or spans

class NotRequested(ContractError):
    '''A proposed step the driver did not ask for; the coordinator leaves it out of the plan.'''

SAVE_START = re.compile(r'(?:remember(?!\s+to\b)|save|store|update|change)\b', re.I)

def asks_action(body):
    '''A clause (without its lead-in) that starts by asking for an action: "Navigate me home", "Save this place…".'''
    return bool(ACTION_START.match(body) or SAVE_START.match(body))

def validate_intent(step,prompt):
    '''Hard safety rules raise; returns whether the evidence uses recognised wording.

    Wording is open-ended, so an unrecognised verb is not grounds for rejection;
    the coordinator sends such write actions to driver confirmation instead.
    The negation and drafting rules apply to the clause that holds the action:
    "Don't call mom" is refused, "Navigate home without tolls" and "Call mom to
    explain I'm late" are not.
    '''
    cap=step['capability']; evidence=step['evidence']
    # Evidence the model paraphrased is not proof the driver asked for it, so it
    # can never count as recognised wording; the step goes to confirmation.
    normal=lambda text:' '.join(re.findall(r'\w+',text.casefold()))
    quoted=normal(evidence) in normal(prompt) if normal(evidence) else False
    recognised=quoted and bool(re.search(CAPABILITIES[cap][2], evidence, re.I))
    region=evidence_region(evidence,prompt);bodies=[clause_body(prompt[a:b]) for a,b in region]
    if CAPABILITIES[cap][1]=='save' and not any(SAVE_START.match(body) for body in bodies):
        # Private data is saved only where the driver asks to save it ("Remember …", "Save … as …"),
        # never as a side effect of another request ("navigate me home" must not re-save home).
        if any(asks_action(clause_body(prompt[a:b])) for a,b in clauses(prompt)):raise NotRequested('Save not asked for')
        raise ContractError('Nothing is saved unless you ask to save it.')
    if not EXPLICIT_ACTION.search(prompt) and any(DRAFTING.match(body) for body in bodies):
        # A step that only a comparison/drafting clause gave rise to ("…compare the routes and give me
        # the fastest") was not asked for. When another clause does ask for an action ("Navigate me
        # home then to work…"), the step is left out; with no action asked anywhere, writes are refused.
        # A read is asked for by a question ("what's my battery"), not by "compare …" (ASKING includes it).
        own=any(asks_action(body) or (CAPABILITIES[cap][1]=='read' and ASKING.match(body) and not DRAFTING.match(body)) for body in bodies)
        if not own and any(asks_action(clause_body(prompt[a:b])) for a,b in clauses(prompt)):
            raise NotRequested('Step comes only from a comparison or drafting clause')
    if CAPABILITIES[cap][1]!='read':
        negated=[]
        for a,b in region:
            clause=prompt[a:b];verb=re.search(CAPABILITIES[cap][2],clause,re.I)
            # Negation counts only before the action verb: "never navigate", not "Play Never Gonna Give You Up".
            if verb:negated.append(bool(NEGATION.search(clause[:verb.start()])))
        # Blocked when every clause asking for this action negates it ("Don't stop the music, play jazz" plays).
        if (negated and all(negated)) or (not negated and STRICT_NEGATION.search(' '.join(prompt[a:b] for a,b in region))):
            raise ContractError('Negated action cannot execute')
        drafting=any(DRAFTING.match(body) for body in bodies)
        # The step's own clause asking for the action ("Navigate home, then compare…") outweighs a drafting clause beside it.
        if drafting and not EXPLICIT_ACTION.search(prompt) and not any(asks_action(body) for body in bodies):
            raise ContractError('Informational or drafting request cannot execute an action')
        if re.search(r'[“”"`]',evidence): raise ContractError('Quoted instructions cannot authorize an action')
    return recognised
